(async () => {
  const checks = [];
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  const click = selector => { const el = document.querySelector(selector); if (!el) throw new Error(`Missing ${selector}`); el.click(); };
  const change = (selector, value) => { const el = document.querySelector(selector); el.value = value; el.dispatchEvent(new Event('change', { bubbles: true })); };
  const check = (selector, value) => { const el = document.querySelector(selector); el.checked = value; el.dispatchEvent(new Event('change', { bubbles: true })); };
  if (document.querySelector('#view-panel').hidden) click('[data-action="toggle-view"]');
  click('[data-action="reset"]');
  if (document.querySelector('[data-action="clear-marks"]')) click('[data-action="clear-marks"]');
  assert(document.querySelector('#scale').value === 'minor-pentatonic', 'Default opens a real scale');
  assert(document.querySelectorAll('.note').length === 96, 'Fifteen-fret board contains 96 positions');
  assert([...document.querySelectorAll('.note')].every(n => n.textContent === ''), 'Dots mode contains no note text');
  assert([...document.querySelectorAll('.string-label span')].every(n => getComputedStyle(n).visibility === 'hidden'), 'String indicators hidden without removing string geometry');
  assert(document.querySelectorAll('.shape-member').length === 4, 'Rectangle contains four pentatonic tones');
  assert(document.querySelector('[data-id="1:5"]').getAttribute('aria-label').includes('A4'), 'Hidden note labels retain accessible pitch');
  assert(document.querySelector('.note.root-note') && document.querySelector('.legend-dot.root'), 'Roots remain identifiable without labels');
  click('[data-action="position"][data-id="1:5"]');
  assert(document.querySelector('.position-inspector').textContent.includes('In rectangle'), 'Inspector states selected-note shape membership');
  change('#scale', 'minor');
  assert(document.querySelectorAll('.shape-member').length === 6, 'Natural minor includes added tones within rectangle');
  assert(document.querySelectorAll('.shape-member.extension-note').length === 2, 'Added scale tones distinguished from skeleton');
  assert(document.querySelectorAll('.marked-note').length === 1, 'Scale changes preserve marks');
  click('[data-action="overlay"][data-value="stack"]');
  assert(document.querySelector('.shape-overlay.stack'), 'Stack overlay renders');
  assert(document.querySelectorAll('.shape-member:not(.extension-note)').length === 6, 'Stack has six pentatonic endpoints');
  click('[data-action="labels"][data-value="both"]');
  assert(document.querySelector('[data-id="1:5"]').textContent === 'AR', 'Both labels retain note and interval semantics');
  change('#root', '0');
  assert(document.querySelector('[data-id="3:5"]').textContent === 'CR', 'Key change transposes named scale');
  assert(document.querySelectorAll('.marked-note').length === 1, 'Key change preserves physical marks');
  change('#scale', 'major');
  change('#root', '1');
  assert(document.querySelector('[data-id="1:1"]').textContent.startsWith('E♯'), 'Named scale spells E-sharp correctly');
  assert(document.querySelector('[data-id="2:1"]').getAttribute('aria-label').startsWith('B♯3'), 'B-sharp uses the correct written octave');
  change('#spelling', 'flats');
  assert(document.querySelector('[data-id="1:1"]').textContent.startsWith('F'), 'Flat key changes spelling without moving pitch');
  // Render both geometric families at each viewport length, orientation and label mode.
  change('#root', '9'); change('#scale', 'minor-pentatonic');
  let cases = 0;
  for (const frets of [12, 15, 24]) for (const left of [false, true]) for (const overlay of ['rectangle', 'stack']) for (const labels of ['none', 'notes', 'intervals', 'both']) {
    change('#frets', String(frets)); check('#leftHanded', left);
    click(`[data-action="overlay"][data-value="${overlay}"]`);
    click(`[data-action="labels"][data-value="${labels}"]`);
    const svg = document.querySelector('.shape-overlay');
    const members = [...document.querySelectorAll('.shape-member')];
    const outline = svg.querySelector('polygon').getBoundingClientRect();
    for (const member of members) {
      const r = member.getBoundingClientRect();
      const cx = (r.left + r.right) / 2, cy = (r.top + r.bottom) / 2;
      if (cx < outline.left || cx > outline.right || cy < outline.top || cy > outline.bottom) throw new Error(`Misaligned ${overlay}/${labels}/${left}/${frets}`);
    }
    if (members.length !== (overlay === 'rectangle' ? 4 : 6)) throw new Error('Wrong shape membership');
    if (document.documentElement.scrollWidth > innerWidth) throw new Error('Page overflow');
    cases++;
  }
  assert(cases === 48, '48 combinations of frets, orientation, shape and labels align geometrically');
  check('#leftHanded', false); change('#frets', '15');
  click('[data-action="overlay"][data-value="rectangle"]');
  click('[data-action="shape-step"][data-direction="1"]');
  click('[data-action="shape-step"][data-direction="1"]');
  assert(document.querySelector('.shape-summary').textContent.includes('G–B offset'), 'Warped shape explicitly identifies tuning adjustment');
  check('#stringNames', true);
  assert(getComputedStyle(document.querySelector('.string-label span')).visibility === 'visible', 'String indicators can be restored');
  click('[data-action="toggle-focus"]');
  check('#focus', true); change('#from', '5'); change('#to', '6');
  assert(!document.querySelector('.shape-overlay'), 'No incomplete shape is drawn');
  assert(document.querySelector('.shape-summary').textContent.includes('No complete shape'), 'Empty focus gives an actionable explanation');
  click('[data-action="focus-clear"]');
  assert(document.querySelector('.shape-overlay'), 'Clearing focus restores shapes');
  change('#scale', 'major-triad');
  assert(!document.querySelector('.shape-overlay'), 'Triad does not pretend to be a pentatonic shape');
  assert(document.querySelector('[data-action="overlay"][data-value="rectangle"]').disabled, 'Unsupported overlays are disabled');
  change('#scale', 'minor-pentatonic');
  click('[data-action="pitch"][data-pitch="1"]');
  assert(document.querySelector('#scale').value === 'custom', 'Editing notes explicitly switches to Custom');
  const selected = [...document.querySelectorAll('.pitch-button.selected')].map(n => n.dataset.pitch).join();
  change('#root', '2');
  assert([...document.querySelectorAll('.pitch-button.selected')].map(n => n.dataset.pitch).join() === selected, 'Custom reference does not transpose selected notes');
  if (document.querySelector('#view-panel').hidden) click('[data-action="toggle-view"]');
  click('[data-action="reset"]');
  if (document.querySelector('[data-action="clear-marks"]')) click('[data-action="clear-marks"]');
  const persisted = JSON.parse(localStorage.getItem('fret-atlas-v1'));
  assert(persisted.scale === 'minor-pentatonic' && persisted.labels === 'none' && persisted.stringNames === false, 'Scale, label mode and string visibility persist');
  return { passed: checks.length, layoutCases: cases, checks };
})();
