// Run with the local browser runner's `eval tests/browser-check.js` on the app page.
(async () => {
  const results = [];
  const assert = (value, description) => { if (!value) throw new Error(description); results.push(description); };
  const click = selector => { const el = document.querySelector(selector); if (!el) throw new Error(`Missing ${selector}`); el.click(); };
  const change = (selector, value) => { const el = document.querySelector(selector); el.value = value; el.dispatchEvent(new Event('change', { bubbles: true })); };
  const check = (selector, value) => { const el = document.querySelector(selector); el.checked = value; el.dispatchEvent(new Event('change', { bubbles: true })); };
  click('[data-action="toggle-view"]');
  assert(!document.querySelector('#view-panel').hidden, 'Display menu opens');
  click('[data-action="reset"]');
  if (document.querySelector('[data-action="clear-marks"]')) click('[data-action="clear-marks"]');
  assert(document.querySelector('#view-panel').hidden, 'Display menu closes after reset');
  assert(document.querySelector('#focus-panel').hidden, 'Focus controls start collapsed');
  change('#scale', 'custom');
  change('#root', '0');
  change('#frets', '12');
  click('[data-action="labels"][data-value="notes"]');
  check('#context', true);
  click('[data-action="none"]');
  click('[data-action="pitch"][data-pitch="0"]');
  assert(document.title.includes('Fret Atlas'), 'Correct application served');
  assert(document.querySelectorAll('.note').length === 78, 'Six strings, open plus twelve frets');
  assert(document.querySelectorAll('.note.highlighted').length === 6, 'Six C notes highlighted initially');
  click('[data-action="pitch"][data-pitch="4"]');
  click('[data-action="pitch"][data-pitch="7"]');
  assert(document.querySelectorAll('.pitch-button.selected').length === 3, 'C E G collection selected');
  for (const id of ['3:5', '2:5', '1:3']) click(`[data-action="position"][data-id="${id}"]`);
  assert(document.querySelectorAll('.marked-note').length === 3, 'Specific triad fingering marked');
  click('[data-action="toggle-focus"]');
  assert(!document.querySelector('#focus-panel').hidden, 'Focus controls expand');
  check('#focus', true);
  for (const string of [4, 5, 6]) click(`[data-action="string"][data-string="${string}"]`);
  assert(document.querySelector('.match-count').textContent === '3 matches', 'Focused C major notes counted on three strings');
  assert(document.querySelectorAll('.marked-note').length === 3, 'Focus preserves all marks');
  click('[data-action="labels"][data-value="both"]');
  assert(document.querySelector('[data-action="position"][data-id="2:5"]').textContent === 'EM3', 'Both labels show note and interval correctly');
  change('#root', '9');
  assert(document.querySelector('[data-action="position"][data-id="3:5"]').textContent === 'Cm3', 'Root change updates interval without transposing notes');
  assert(document.querySelectorAll('.marked-note').length === 3, 'Root change preserves fingering');
  click('[data-action="toggle-view"]');
  change('#spelling', 'flats');
  assert(document.querySelector('[data-action="position"][data-id="1:2"]').textContent.startsWith('G♭'), 'Flat spelling uses same physical pitch');
  change('#frets', '24');
  assert(document.querySelectorAll('.note').length === 150, 'Twenty-four-fret board has 150 positions');
  click('[data-action="position"][data-id="1:24"]');
  change('#frets', '12');
  assert(document.querySelectorAll('.mark-chip').length === 4, 'Hidden high-fret marks retained');
  assert(document.querySelector('.marks-list').textContent.includes('off-screen'), 'Hidden marks have an off-screen indicator');
  if (document.querySelector('#view-panel').hidden) click('[data-action="toggle-view"]');
  check('#leftHanded', true);
  assert(document.querySelector('.fret-number-row').lastElementChild.textContent === 'OPEN', 'Left-handed view puts open notes on right');
  assert(getComputedStyle(document.querySelector('.open-cell')).borderLeftWidth === '4px', 'Nut mirrored to correct edge');
  let note = document.querySelector('[data-action="position"][data-id="1:3"]');
  note.focus();
  note.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  assert(document.activeElement.dataset.id === '1:2', 'Arrow navigation follows left-handed visual direction');
  check('#context', false);
  document.querySelector('#context').dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  assert(document.querySelector('#view-panel').hidden, 'Escape dismisses display menu');
  assert(document.activeElement.dataset.key === 'toggle-view', 'Escape returns focus to Display');
  assert(document.querySelectorAll('.concealed-note').length > 0, 'Other notes can be hidden');
  assert(document.querySelectorAll('.marked-note.concealed-note').length === 0, 'Marks remain visible when other notes are hidden');
  click('[data-action="help"]');
  assert(document.querySelector('dialog').open, 'Help opens as modal');
  click('[data-action="close-help"]');
  assert(!document.querySelector('dialog').open, 'Help closes');
  click('[data-action="toggle-view"]');
  click('[data-action="reset"]');
  assert(document.querySelectorAll('.mark-chip').length === 4, 'Reset view preserves marks');
  click('[data-action="clear-marks"]');
  assert(document.querySelectorAll('.mark-chip').length === 0, 'Clear marks removes marks');
  assert(!document.querySelector('.marks-section'), 'Empty marks section is removed');
  assert(!document.querySelector('.sidebar'), 'No sidebar competes with the fretboard');
  assert(!document.querySelector('.selection-card'), 'Palette replaces duplicate note collection');
  click('[data-action="toggle-view"]');
  document.querySelector('h1').click();
  assert(document.querySelector('#view-panel').hidden, 'Outside click dismisses display menu');
  assert(!document.querySelector('dialog').open, 'Help stays closed after subsequent renders');
  const shapeBounds = document.querySelector('.shape-overlay polygon').getBoundingClientRect();
  const boardBounds = document.querySelector('.board-scroll').getBoundingClientRect();
  assert(shapeBounds.left >= boardBounds.left && shapeBounds.right <= boardBounds.right, 'Reset brings the default rectangle into view');
  assert(document.querySelectorAll('.note[tabindex="0"]').length === 1, 'Board has one roving keyboard tab stop');
  assert(document.documentElement.scrollWidth <= innerWidth, 'Page fits viewport; only board scrolls horizontally');
  assert(JSON.parse(localStorage.getItem('fret-atlas-v1')).marks.length === 0, 'State persisted to local storage');
  return { passed: results.length, checks: results };
})();
